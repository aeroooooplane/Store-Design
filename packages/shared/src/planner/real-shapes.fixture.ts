import type { ShopType } from '../enums.ts'
import { SpaceSchema } from '../schemas/space.ts'
import type { Space } from '../schemas/space.ts'

export interface RealShape {
  /** The store, e.g. store-0293 (PDF-293 in 资源库/09_门店档案). */
  source: string
  name: string
  shopType: ShopType
  space: Space
}

type Pt = [number, number]

const real = (
  source: string,
  name: string,
  shopType: ShopType,
  height: number,
  boundary: Pt[],
  entrances: { a: Pt; b: Pt; kind: 'main' | 'side' }[],
): RealShape => ({
  source,
  name,
  shopType,
  space: SpaceSchema.parse({
    schemaVersion: 1,
    boundary,
    height,
    entrances,
  }),
})

