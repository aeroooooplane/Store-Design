import type { ShopType } from '../enums.ts'
import { SpaceSchema } from '../schemas/space.ts'
import type { Space } from '../schemas/space.ts'

export interface RealShape {
  /** Source folder in the cleaning pilot, e.g. store-0293. */
  source: string
  name: string
  shopType: ShopType
  space: Space
}

type Pt = [number, number]

const real = (
  source: string,
  name: string,
  shopType: ShopType,
  height: number,
  boundary: Pt[],
  entrance: [Pt, Pt],
): RealShape => ({
  source,
  name,
  shopType,
  space: SpaceSchema.parse({
    schemaVersion: 1,
    boundary,
    height,
    entrances: [{ a: entrance[0], b: entrance[1], kind: 'main' }],
  }),
})

